#!/usr/bin/env python3
"""Generate diploma plan (план ВКР) for OrderFlow project."""

from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH

doc = Document()

for s in doc.sections:
    s.top_margin    = Cm(2)
    s.bottom_margin = Cm(2)
    s.left_margin   = Cm(3)
    s.right_margin  = Cm(1.5)

F = 'Times New Roman'

def p(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, sz=14, bold=False,
      indent=True, sb=0, sa=4):
    par = doc.add_paragraph()
    par.alignment = align
    par.paragraph_format.space_before = Pt(sb)
    par.paragraph_format.space_after  = Pt(sa)
    if indent and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        par.paragraph_format.first_line_indent = Cm(1.25)
    if text:
        r = par.add_run(text)
        r.font.name = F; r.font.size = Pt(sz); r.font.bold = bold
    return par

def center(text, sz=14, bold=False, sb=2, sa=2):
    return p(text, WD_ALIGN_PARAGRAPH.CENTER, sz=sz, bold=bold, indent=False,
             sb=sb, sa=sa)

def left(text, sz=14, bold=False, sb=2, sa=2, li=0):
    par = p(text, WD_ALIGN_PARAGRAPH.JUSTIFY, sz=sz, bold=bold, indent=False,
            sb=sb, sa=sa)
    if li:
        par.paragraph_format.left_indent = Cm(li)
    return par

