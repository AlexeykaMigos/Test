# ─── Helpers ────────────────────────────────────────────────────────────────
FONT = 'Times New Roman'

def para(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14,
         bold=False, indent_first=True, space_before=0, space_after=6):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after  = Pt(space_after)
    if indent_first and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        pf.first_line_indent = Cm(1.25)
    if text:
        r = p.add_run(text)
        r.font.name = FONT
        r.font.size = Pt(size)
        r.font.bold = bold
    return p

def heading(text, space_before=12):
    """Bold, centred, 14pt heading (no indent)."""
    p = para(text, align=WD_ALIGN_PARAGRAPH.CENTER,
             size=14, bold=True, indent_first=False,
             space_before=space_before, space_after=6)
    return p

def subheading(text, space_before=10):
    """Bold left-aligned 14pt subheading."""
    p = para(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
             size=14, bold=True, indent_first=False,
             space_before=space_before, space_after=6)
    return p

def bullet(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.left_indent       = Cm(1.25)
    pf.first_line_indent = Cm(0)
    pf.space_after       = Pt(4)
    r = p.add_run(text)
    r.font.name = FONT
    r.font.size = Pt(14)
    return p

def numbered_task(num, text):
    """Numbered paragraph like in the template (indent, number at start)."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(6)
    r = p.add_run(f'{num}. {text}')
    r.font.name = FONT
    r.font.size = Pt(14)
    return p

def code_block(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.left_indent = Cm(1.25)
    r = p.add_run(text)
    r.font.name = 'Courier New'
    r.font.size = Pt(10)
    return p

def pb():
    doc.add_page_break()

