from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH

doc = Document()

for section in doc.sections:
    section.top_margin    = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin   = Cm(3)
    section.right_margin  = Cm(1.5)

FONT = 'Times New Roman'
SIZE = 14

def p(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False,
      indent=True, sb=0, sa=6):
    par = doc.add_paragraph()
    par.alignment = align
    par.paragraph_format.space_before = Pt(sb)
    par.paragraph_format.space_after  = Pt(sa)
    if indent and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        par.paragraph_format.first_line_indent = Cm(1.25)
    if text:
        r = par.add_run(text)
        r.font.name = FONT
        r.font.size = Pt(SIZE)
        r.font.bold = bold
    return par

def h1(text):
    return p(text, align=WD_ALIGN_PARAGRAPH.CENTER, bold=True,
             indent=False, sb=14, sa=8)

def h2(text):
    return p(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=True,
             indent=False, sb=12, sa=6)

def ntask(num, text):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    par.paragraph_format.first_line_indent = Cm(1.25)
    par.paragraph_format.space_after = Pt(6)
    r = par.add_run(f'{num}. {text}')
    r.font.name = FONT
    r.font.size = Pt(SIZE)
    return par

def pb(): doc.add_page_break()

